# Define the 7 tetrominoes, each with 4 rotation states, as 4x4 ASCII grids.
# bit index = row*4+col (row-major), bit=1 means filled. Encoded as a 16-bit value per rotation.

PIECES = {
    'I': [
        ["....","####","....","...."],
        ["..#.","..#.","..#.","..#."],
        ["....","####","....","...."],
        ["..#.","..#.","..#.","..#."],
    ],
    'O': [
        [".##.",".##.","....","...."],
    ]*4,
    'T': [
        [".#..","###.","....","...."],
        [".#..","##..",".#..","...."],
        ["....","###.",".#..","...."],
        ["..#.","##..","..#.","...."],
    ],
    'S': [
        ["....",".##.","##..","...."],
        ["#...","##..",".#..","...."],
        ["....",".##.","##..","...."],
        ["#...","##..",".#..","...."],
    ],
    'Z': [
        ["....","##..",".##.","...."],
        [".#..","##..","#...","...."],
        ["....","##..",".##.","...."],
        [".#..","##..","#...","...."],
    ],
    'J': [
        ["#...","###.","....","...."],
        [".##.",".#..",".#..","...."],
        ["....","###.","..#.","...."],
        [".#..",".#..","##..","...."],
    ],
    'L': [
        ["..#.","###.","....","...."],
        [".#..",".#..",".##.","...."],
        ["....","###.","#...","...."],
        ["##..",".#..",".#..","...."],
    ],
}

order = ['I','O','T','S','Z','J','L']
all_vals = []
for name in order:
    print(f"=== {name} ===")
    for rot in PIECES[name]:
        v = 0
        for i, ch in enumerate(''.join(rot)):
            if ch == '#':
                v |= (1 << i)
        all_vals.append(v)
        for r in range(4):
            print(rot[r])
        print(f"  -> 0x{v:04x}")
    print()

print("order:", order)
print("total rotation entries:", len(all_vals))
print(','.join(str(v) for v in all_vals))
