# encode: 1 byte per row, bits 4..0 = leftmost..rightmost pixel (bit4=col0)
def encode(rows):
    out = []
    for r in rows:
        b = 0
        for i,c in enumerate(r):
            if c == '#':
                b |= (1 << (4 - i))
        out.append(b)
    return out

